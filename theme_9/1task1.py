# Класс, представляющий один томат
class Tomato:
    # Словарь состояний томата с соответствующими описаниями
    states = {0: 'отсутствует', 1: 'цветение', 2: 'зелёный', 3: 'красный'}

    def __init__(self, index):
        # Уникальный индекс томата для идентификации
        self._index = index
        # Начальное состояние томата - "отсутствует" (0)
        self._state = 0  

    # Метод для роста томата на одну стадию
    def grow(self):
        # Проверяем, не достиг ли томат максимальной стадии зрелости
        if self._state < 3:
            self._state += 1  # Переходим на следующую стадию
        # Выводим информацию о текущем состоянии томата
        print(f"Томат {self._index} теперь {Tomato.states[self._state]}.")

    # Метод проверки, созрел ли томат полностью
    def is_ripe(self):
        return self._state == 3  # Возвращает True если томат красный

# Класс, представляющий куст томатов (коллекцию томатов)
class TomatoBush:
    def __init__(self, num):
        # Создаем список томатов заданного количества
        self.tomatoes = [Tomato(index) for index in range(1, num + 1)]

    # Метод для роста всех томатов на кусте
    def grow_all(self):
        print("\nКуст растёт...")
        # Проходим по всем томатам и вызываем метод grow для каждого
        for tomato in self.tomatoes:
            tomato.grow()

    # Метод проверки, все ли томаты созрели
    def all_are_ripe(self):
        # Используем функцию all() для проверки всех томатов
        return all(tomato.is_ripe() for tomato in self.tomatoes)

    # Метод сбора урожая (очистка списка томатов)
    def give_away_all(self):
        self.tomatoes.clear()  # Удаляем все томаты из списка
        print("Урожай собран")

# Класс садовника, который ухаживает за кустом томатов
class Gardener:
    def __init__(self, name, plant):
        self.name = name  # Имя садовника
        self._plant = plant  # Куст томатов, за которым ухаживает садовник

    # Метод для работы садовника (уход за растениями)
    def work(self):
        print(f"\n{self.name} ухаживает за растением.")
        self._plant.grow_all()  # Вызываем рост всех томатов
        print(f"{self.name} закончила работу.")

    # Метод сбора урожая
    def harvest(self):
        print(f"\n{self.name} проверяет урожай...")
        # Проверяем, все ли томаты созрели
        if self._plant.all_are_ripe():
            self._plant.give_away_all()  # Собираем урожай
            print(f"{self.name} собрала урожай.")
        else:
            print("не все томаты созрели!")  # Сообщение если урожай не готов

    # Статический метод - справочная информация (не требует создания объекта)
    @staticmethod
    def knowledge_base():
        print("""Справка по садоводству:
1. Томат проходит стадии: отсутствует - цветение - зелёный - красный.
2. Чтобы получить урожай, необходимо ухаживать за кустом до полного созревания.
3. После созревания все плоды можно собрат""")  # Опечатка: "собрат" вместо "собрать"

# Основная часть программы, которая выполняется при запуске скрипта
if __name__ == "__main__":
    # Выводим справочную информацию
    Gardener.knowledge_base()

    # Создаем куст с 3 томатами
    bush = TomatoBush(3)
    # Создаем садовника по имени Елена
    gardener = Gardener("Елена", bush)

    # Первый цикл ухода и проверки урожая
    gardener.work()    # Елена ухаживает за растениями
    gardener.harvest() # Проверяет, готов ли урожай

    # Второй цикл ухода и проверки урожая
    gardener.work()    # Продолжаем ухаживать
    gardener.harvest() # Снова проверяем урожай

    # Третий цикл ухода и проверки урожая
    gardener.work()    # Последний уход
    gardener.harvest() # Должны собрать урожай (все томаты созрели)